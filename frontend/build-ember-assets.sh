#!/usr/bin/env bash
# Build the pinned Discourse core Ember browser modules in an isolated staging tree.
# Run from repo root after source harness/env.sh.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
DISCOURSE="$ROOT/discourse"
BUILD="$ROOT/minimal/build"
STAGE="$BUILD/.frontend-ember-stage"
OUTPUT="$BUILD/assets/discourse"
SOURCE_NODE_MODULES="$DISCOURSE/frontend/discourse/node_modules"

if [[ ! -f "$DISCOURSE/frontend/discourse/rolldown.config.mjs" ]]; then
  echo "missing Discourse frontend source at $DISCOURSE/frontend/discourse" >&2
  exit 2
fi
if [[ ! -d "$SOURCE_NODE_MODULES" ]]; then
  echo "missing installed frontend dependencies at $SOURCE_NODE_MODULES" >&2
  exit 2
fi
if [[ -e "$OUTPUT" ]]; then
  echo "refusing to overwrite existing assets: $OUTPUT" >&2
  exit 2
fi
if [[ -e "$STAGE" ]]; then
  echo "refusing to reuse staging path: $STAGE" >&2
  exit 2
fi

mkdir -p "$BUILD"
trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE"
cp -a "$DISCOURSE/frontend/discourse" "$STAGE/app"
rm -rf "$STAGE/app/node_modules" "$STAGE/app/dist"
mkdir -p "$STAGE/app/node_modules"

# Make isolated node_modules links. Point dependency links at resolved package
# locations, while keeping .embroider (generated by rolldown.config.mjs) local.
shopt -s nullglob dotglob
for entry in "$SOURCE_NODE_MODULES"/*; do
  name="$(basename "$entry")"
  [[ "$name" == ".bin" || "$name" == ".embroider" ]] && continue
  if [[ -d "$entry" && "$name" == @* ]]; then
    mkdir -p "$STAGE/app/node_modules/$name"
    for scoped_entry in "$entry"/*; do
      [[ -e "$scoped_entry" ]] || continue
      ln -s "$(realpath "$scoped_entry")" "$STAGE/app/node_modules/$name/$(basename "$scoped_entry")"
    done
  else
    ln -s "$(realpath "$entry")" "$STAGE/app/node_modules/$name"
  fi
done
if [[ -d "$SOURCE_NODE_MODULES/.bin" ]]; then
  ln -s "$(realpath "$SOURCE_NODE_MODULES/.bin")" "$STAGE/app/node_modules/.bin"
fi

# Rolldown is the actual Discourse core frontend build. Invoke its preinstalled
# CLI directly to avoid pnpm's workspace/dependency preflight (which may fetch).
# The hard timeout bounds CPU/runtime; this is not Rails asset precompile.
(
  cd "$STAGE/app"
  timeout --signal=TERM --kill-after=15s 600s \
    env CI=1 EMBER_ENV=production node node_modules/rolldown/bin/cli.mjs -c rolldown.config.mjs
)

[[ -f "$STAGE/app/dist/manifest/manifest.json" ]] || {
  echo "build finished without expected dist/manifest/manifest.json" >&2
  exit 1
}
mkdir -p "$(dirname "$OUTPUT")"
mv "$STAGE/app/dist" "$OUTPUT"
echo "Discourse core Ember JS assets: $OUTPUT"
echo "Note: this does not build Rails CSS, plugin/theme assets, or the HTML document."
