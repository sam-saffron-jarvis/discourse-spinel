# frozen_string_literal: true

require "minitest/autorun"
require "json"
require "uri"
require_relative "native_document"

class NativeDocumentTest < Minitest::Test
  def test_prefixed_bootstrap_uses_real_assets_and_safe_preload_json
    title = "</ScRiPt><img src=x> & <!-- comment -->"
    preloads = { "topic_list" => JSON.generate("topics" => [{ "title" => title }]) }
    html = NativeDocument.new("/node/jarvis/widgets/discourse-spinel-app").render(
      preloads,
      { "default_locale" => "en", "secret_site_setting" => "must-not-leak" },
      "https://hub.samsaffron.com",
    )

    assert_includes html, 'id="data-preloaded"'
    assert_includes html, 'id="main"'
    refute_match(/<table\b/i, html)
    refute_includes html, "must-not-leak"
    assert_includes html, 'data-base-uri="/node/jarvis/widgets/discourse-spinel-app"'
    assert_match(%r{href="/node/jarvis/widgets/discourse-spinel-app/assets/native/css/common.css"}, html)
    assert_match(%r{href="/node/jarvis/widgets/discourse-spinel-app/assets/native/css/color-definitions.css"}, html)
    assert_match(%r{src="/node/jarvis/widgets/discourse-spinel-app/assets/native/locale/en.js"}, html)
    boot = JSON.parse(html[/<script type="application\/json" id="native-boot-assets">(.*?)<\/script>/m, 1])
    assert_match(%r{\A/node/jarvis/widgets/discourse-spinel-app/assets/discourse/assets/js/discourse-.*\.digested\.js\z}, boot.fetch("entry"))
    assert_equal boot.fetch("entry"), boot.fetch("modules").last
    assert_equal boot.fetch("modules").uniq, boot.fetch("modules")
    refute_match(/<link rel="modulepreload"/, html)
    refute_match(/<script type="module" src="[^"]*\/assets\/js\/discourse-[^"]*"/, html)
    assert_includes html, 'for (const url of boot.modules) { await preload(url); }'
    assert_includes html, 'await import(boot.locale);'
    assert_includes html, 'await import(boot.entry);'
    assert_includes html, 'notice.id = "native-boot-error";'

    preload_body = html[/<script type="application\/json" id="data-preloaded">(.*?)<\/script>/m, 1]
    refute_nil preload_body
    refute_includes preload_body, "<"
    unpacked = JSON.parse(preload_body)
    assert_equal title, JSON.parse(unpacked.fetch("topic_list")).dig("topics", 0, "title")

    encoded = html[/<meta name="discourse\/config\/environment" content="([^"]+)"/, 1]
    config = JSON.parse(URI.decode_www_form_component(encoded))
    assert_equal "/node/jarvis/widgets/discourse-spinel-app", config.fetch("rootURL")
    assert_equal "production", config.fetch("environment")

    worker = NativeDocument.new("/node/jarvis/widgets/discourse-spinel-app").render_service_worker(
      "https://hub.samsaffron.com",
    )
    assert_includes worker, "https://hub.samsaffron.com/node/jarvis/widgets/discourse-spinel-app/push_notifications/subscribe"
    assert_includes worker, "var SHARE_TARGET_PATH = '/node/jarvis/widgets/discourse-spinel-app/share-target';"
    assert_includes worker, 'self.addEventListener(\'push\''
    refute_includes worker, "__MINIMAL_BASE_"
  end

  def test_original_plugin_loader_is_paced_and_enabled_only
    prefix = "/node/jarvis/widgets/discourse-spinel-app"
    document = NativeDocument.new(prefix)
    html = document.render({}, { "discourse_reactions_enabled" => true }, "http://127.0.0.1:3529")
    boot = JSON.parse(html[/<script type="application\/json" id="native-boot-assets">(.*?)<\/script>/m, 1])
    plugin = boot.fetch("plugins").fetch(0)
    assert_equal "discourse-reactions", plugin.fetch("name")
    assert_equal plugin.fetch("entry"), plugin.fetch("modules").last
    assert plugin.fetch("modules").all? { |path| path.start_with?("#{prefix}/assets/reactions-core/") }
    assert_includes html, 'link.dataset.pluginName = plugin.name;'
    assert_operator html.index('for (const plugin of boot.plugins)'), :<, html.index('await import(boot.entry);')
    refute_match(/<link rel="modulepreload"/, html)
    assert_includes html, "#{prefix}/assets/native/css/discourse-reactions.css"
    disabled = document.render({}, { "discourse_reactions_enabled" => false }, "http://127.0.0.1:3529")
    data = JSON.parse(disabled[/<script type="application\/json" id="native-boot-assets">(.*?)<\/script>/m, 1])
    assert_equal [], data.fetch("plugins")
  end

  def test_details_stylesheet_selection_does_not_rewrite_stored_cooked
    prefix = "/node/jarvis/widgets/discourse-spinel-app"
    document = NativeDocument.new(prefix)
    # Opaque bootstrap payload only, not positive details/cooking evidence (the
    # latter is generated by actual PrettyText.cook in details-test).
    cooked = 'opaque stored cooked bytes <>&'
    payload = { "id" => 42, "post_stream" => { "posts" => [{ "cooked" => cooked }] } }
    preloads = { "topic_42" => JSON.generate(payload) }
    [true, false].each do |enabled|
      html = document.render(preloads, { "details_enabled" => enabled }, "http://127.0.0.1:3529",
                             topic: { id: 42, slug: "stored", title: "Stored" })
      assert_equal enabled, html.include?("#{prefix}/assets/native/css/discourse-details.css")
      raw = JSON.parse(html[/<script type="application\/json" id="data-preloaded">(.*?)<\/script>/m, 1])
      assert_equal cooked, JSON.parse(raw.fetch("topic_42")).dig("post_stream", "posts", 0, "cooked")
      boot = JSON.parse(html[/<script type="application\/json" id="native-boot-assets">(.*?)<\/script>/m, 1])
      refute boot.fetch("plugins").any? { |plugin| plugin["name"] == "discourse-details" }
      refute_includes html, "apply-details"
    end
  end

  def test_topic_document_uses_real_topic_preload_and_canonical_url
    topic_id = 123
    title = "Actual topic title <safe>"
    payload = { "id" => topic_id, "title" => title, "post_stream" => { "posts" => [] } }
    html = NativeDocument.new("/node/jarvis/widgets/discourse-spinel-app").render(
      { "topic_#{topic_id}" => JSON.generate(payload) },
      { "title" => "Forum", "default_locale" => "en" },
      "https://hub.samsaffron.com",
      topic: { id: topic_id, slug: "actual-topic-title", title: title },
    )

    assert_includes html, "<title>Actual topic title &lt;safe&gt; - Forum</title>"
    assert_includes html, '<link rel="canonical" href="https://hub.samsaffron.com/node/jarvis/widgets/discourse-spinel-app/t/actual-topic-title/123">'
    refute_includes html, 'discourse_current_homepage" content="latest'
    body = html[/<script type="application\/json" id="data-preloaded">(.*?)<\/script>/m, 1]
    assert_equal payload, JSON.parse(JSON.parse(body).fetch("topic_123"))
  end

  def test_topic_document_requires_matching_topic_preload_and_safe_route_fields
    document = NativeDocument.new("")
    topic = { id: 42, slug: "topic", title: "Topic" }
    assert_raises(ArgumentError) { document.render({}, {}, "http://127.0.0.1:3498", topic:) }
    assert_raises(ArgumentError) do
      document.render({ "topic_42" => "{}" }, {}, "http://127.0.0.1:3498", topic: topic.merge(slug: "a/b"))
    end
  end

  def test_boot_graph_is_dependency_first
    document = NativeDocument.new("")
    descriptor = JSON.parse(File.read(NativeDocument::DEFAULT_STAGE_MANIFEST))
    chunks = descriptor.fetch("core_ember").fetch("chunks")
    entry = descriptor.fetch("core_ember").fetch("entrypoints").fetch("discourse")
    ordered = document.send(:dependency_files, entry, chunks)
    positions = ordered.each_with_index.to_h
    assert_equal entry, ordered.last
    ordered.each do |filename|
      Array(chunks.fetch(filename, {})["imports"]).each do |dependency|
        assert_operator positions.fetch(dependency), :<, positions.fetch(filename),
                        "#{dependency} must preload before #{filename}"
      end
    end
  end

  def test_rejects_traversal_prefix_and_bad_preload_json
    assert_raises(ArgumentError) { NativeDocument.new("/a/../b") }
    assert_raises(JSON::ParserError) do
      NativeDocument.new("").render({ "site" => "not json" }, {}, "http://127.0.0.1:3498")
    end
  end
end
